export function getCommunesByWilaya(wilayaCode: number): Commune[] {
  return COMMUNES.filter(c => c.wilayaCode === wilayaCode);
}

export function getWilayaByCode(code: number): Wilaya | undefined {
  return WILAYAS.find(w => w.code === code);
}

export function getCommuneCoords(wilayaCode: number, communeName: string): [number, number] | null {
  const commune = COMMUNES.find(c => c.wilayaCode === wilayaCode && c.name === communeName);
  if (commune?.lat && commune?.lng) return [commune.lat, commune.lng];
  const wilaya = getWilayaByCode(wilayaCode);
  if (wilaya) return [wilaya.lat, wilaya.lng];
  return null;
}
